"""Regenerate ``src/azazel_fabric/testing/_producer_capture_data.py``.

The captures live as reviewable JSON under ``tests/fixtures/producer_captures/``
with a ``provenance.json`` per product. The wheel ships no data files (there is
no package-data configuration), so the same bytes are embedded as Python string
literals. ``tests/test_producer_captures.py`` fails if the two ever disagree, so
run this after changing a fixture:

    python3 tools/producer_captures/embed.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
FIXTURES = REPO / "tests" / "fixtures" / "producer_captures"
OUT = REPO / "src" / "azazel_fabric" / "testing" / "_producer_capture_data.py"


def build() -> str:
    lines = [
        '"""Generated by tools/producer_captures/embed.py. Do not edit by hand."""',
        "",
        "# fmt: off",
        "CAPTURES = {",
    ]
    for product_dir in sorted(p for p in FIXTURES.iterdir() if p.is_dir()):
        provenance = json.loads((product_dir / "provenance.json").read_text(encoding="utf-8"))
        product = provenance["product"]
        for stem, meta in sorted(provenance["captures"].items()):
            payload = (product_dir / f"{stem}.json").read_text(encoding="utf-8")
            record = {
                "product": product,
                "repository": provenance["repository"],
                "commit": provenance["commit"],
                "fabric_pin": provenance["fabric_pin"],
                "captured": provenance["captured"],
                **meta,
                "payload_json": payload,
            }
            lines.append(f"    {product + '/' + stem + '_v0'!r}: {{")
            for key in sorted(record):
                lines.append(f"        {key!r}: {record[key]!r},")
            lines.append("    },")
    lines += ["}", "# fmt: on", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
